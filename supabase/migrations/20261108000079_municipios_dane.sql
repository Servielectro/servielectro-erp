create table if not exists public.municipios_dane (
  codigo text primary key check (codigo ~ '^[0-9]{5}$'),
  departamento_codigo text not null check (departamento_codigo ~ '^[0-9]{2}$'),
  departamento text not null,
  municipio text not null,
  tipo text not null,               -- Municipio / Área no municipalizada / Isla
  fuente text not null default 'DANE DIVIPOLA (datos.gov.co gdxc-w37w), actualizado 2025-01-24',
  check (left(codigo, 2) = departamento_codigo)
);
create index if not exists idx_municipios_dane_dpto on public.municipios_dane (departamento_codigo, municipio);
comment on table public.municipios_dane is 'DIVIPOLA del DANE. Fuente: datos.gov.co dataset gdxc-w37w, actualizado 2025-01-24, descargado 2026-10-27.';

